create policy "profiles are public" on public.profiles for select using (true);
create policy "users update own profile" on public.profiles for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

create policy "questions are public" on public.questions for select using (true);
create policy "authenticated users create questions" on public.questions for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "authors update questions" on public.questions for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "authors delete questions" on public.questions for delete to authenticated using ((select auth.uid()) = user_id);

create policy "answers are public" on public.answers for select using (true);
create policy "authenticated users create answers" on public.answers for insert to authenticated with check ((select auth.uid()) = user_id);
create policy "authors update answers" on public.answers for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "authors delete answers" on public.answers for delete to authenticated using ((select auth.uid()) = user_id);

create policy "tags are public" on public.tags for select using (true);
create policy "authenticated users create tags" on public.tags for insert to authenticated with check (true);
create policy "question tags are public" on public.question_tags for select using (true);
create policy "authors add question tags" on public.question_tags for insert to authenticated with check (exists (select 1 from public.questions q where q.id = question_id and q.user_id = (select auth.uid())));
create policy "authors delete question tags" on public.question_tags for delete to authenticated using (exists (select 1 from public.questions q where q.id = question_id and q.user_id = (select auth.uid())));

